const targetFile = path.resolve(__dirname, '../src/data/translationsExtended.ts');
let content = fs.readFileSync(targetFile, 'utf8');

// We have EXTENDED_TRANSLATIONS with en, hi, kn, ta, te, ml, mr
const langs = ['en', 'hi', 'kn', 'ta', 'te', 'ml', 'mr'];

for (const lang of langs) {
  // Find where `[lang]: {` starts in EXTENDED_TRANSLATIONS
  const langRegex = new RegExp(`(\\b${lang}:\\s*\\{[\\s\\S]*?\\n\\s*\\},)`, 'm');
  const match = content.match(langRegex);
  if (!match) {
    console.error(`Could not match ${lang} section in translationsExtended.ts`);
    continue;
  }

  // Create entries to insert before the closing `},`
  const entries = [];
  for (const [key, trMap] of Object.entries(NEW_BATCH)) {
    const val = trMap[lang] || trMap['en'] || key;
    // Check if key already in this section
    const keyEscaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    if (!new RegExp(`'${keyEscaped}':`).test(match[0])) {
      entries.push(`    '${key.replace(/'/g, "\\'")}': '${val.replace(/'/g, "\\'")}',`);
    }
  }

  if (entries.length > 0) {
    const replacement = match[0].replace(/\n\s*\},$/, '\n' + entries.join('\n') + '\n  },');
    content = content.replace(match[0], replacement);
    console.log(`Added ${entries.length} keys to ${lang}`);
  }
}

fs.writeFileSync(targetFile, content, 'utf8');
console.log('Successfully updated translationsExtended.ts!');
